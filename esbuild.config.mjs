import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";

// Node builtins, bare and `node:`-prefixed (Obsidian desktop provides them).
const builtins = [...builtinModules, ...builtinModules.map((m) => `node:${m}`)];

const banner = `/*
This file is auto-generated by esbuild. Do not edit directly.
Source lives in src/. See https://github.com/adrian-moll/obsidian-selfsync
*/`;

const production = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: production,
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
