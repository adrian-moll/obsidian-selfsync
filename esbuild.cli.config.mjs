/**
 * Build the headless client (src/headless/cli.ts) into a single Node bundle,
 * dist/selfsync-cli.cjs, which docker/Dockerfile.cli runs.
 *
 * Separate from esbuild.config.mjs because the two targets share no settings:
 * the plugin is an Obsidian CJS bundle with `obsidian` external, this is a Node
 * program where importing `obsidian` is a BUILD ERROR. That guard matters —
 * `obsidian` is a devDependency, so a stray import would otherwise bundle
 * happily and only fail at runtime inside the container.
 */
import esbuild from "esbuild";
import process from "node:process";

const banner = `#!/usr/bin/env node
/*
This file is auto-generated by esbuild. Do not edit directly.
Source lives in src/headless/. See https://github.com/adrian-moll/obsidian-selfsync
*/`;

const production = process.argv[2] === "production";

/** Fail the build if anything on the headless path reaches for Obsidian/Electron. */
const forbidAppImports = {
  name: "forbid-app-imports",
  setup(build) {
    build.onResolve({ filter: /^(obsidian|electron)$/ }, (args) => ({
      errors: [
        {
          text: `"${args.path}" must never be imported by the headless client (from ${args.importer})`,
        },
      ],
    }));
  },
};

const options = {
  banner: { js: banner },
  entryPoints: ["src/headless/cli.ts"],
  bundle: true,
  platform: "node", // node builtins stay external automatically
  format: "cjs",
  target: "node20",
  plugins: [forbidAppImports],
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "dist/selfsync-cli.cjs",
  minify: false, // a readable stack trace beats a few hundred KB in a container
};

if (production) {
  await esbuild.build(options);
} else {
  const context = await esbuild.context(options);
  await context.watch();
}
